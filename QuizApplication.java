import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Scanner;

public class QuizApplication {

    static final String URL = "jdbc:oracle:thin:@//localhost:1521/FREEPDB1";
    static final String USER = "QUIZUSER";
    static final String PASSWORD = System.getenv("QUIZ_DB_PASSWORD");

    static Scanner sc = new Scanner(System.in);

    static Connection connect() throws SQLException {

        if (PASSWORD == null || PASSWORD.isBlank()) {
            throw new SQLException(
                "QUIZ_DB_PASSWORD is not set. Set it in PowerShell before running."
            );
        }

        return DriverManager.getConnection(URL, USER, PASSWORD);
    }

    static void createTable() {

        String sql = """
            CREATE TABLE QUIZ_RESULTS (
                ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                STUDENT_ID VARCHAR2(20) NOT NULL,
                QUIZ_NAME VARCHAR2(100) NOT NULL,
                TOTAL_QUESTIONS NUMBER NOT NULL,
                SCORE NUMBER NOT NULL,
                PERCENTAGE NUMBER(5,2) NOT NULL
            )
            """;

        try (Connection con = connect();
             Statement stmt = con.createStatement()) {

            stmt.executeUpdate(sql);
            System.out.println("QUIZ_RESULTS table created successfully.");

        } catch (SQLException e) {

            if (e.getErrorCode() == 955) {
                System.out.println("QUIZ_RESULTS table already exists.");
            } else {
                System.out.println("Table creation failed: " + e.getMessage());
                System.out.println("Oracle error code: " + e.getErrorCode());
            }
        }
    }

    static void addResult() {

        try {

            System.out.print("Enter student ID: ");
            String studentId = sc.nextLine().trim();

            System.out.print("Enter quiz name: ");
            String quizName = sc.nextLine().trim();

            System.out.print("Enter total number of questions: ");
            int totalQuestions = Integer.parseInt(sc.nextLine().trim());

            System.out.print("Enter score: ");
            int score = Integer.parseInt(sc.nextLine().trim());

            if (studentId.isEmpty() || quizName.isEmpty()) {
                System.out.println("Student ID and quiz name cannot be empty.");
                return;
            }

            if (totalQuestions <= 0) {
                System.out.println("Total questions must be greater than 0.");
                return;
            }

            if (score < 0 || score > totalQuestions) {
                System.out.println("Score must be between 0 and total questions.");
                return;
            }

            double percentage = (score * 100.0) / totalQuestions;

            String sql = """
                INSERT INTO QUIZ_RESULTS
                (STUDENT_ID, QUIZ_NAME, TOTAL_QUESTIONS, SCORE, PERCENTAGE)
                VALUES (?, ?, ?, ?, ?)
                """;

            try (Connection con = connect();
                 PreparedStatement ps = con.prepareStatement(sql)) {

                ps.setString(1, studentId);
                ps.setString(2, quizName);
                ps.setInt(3, totalQuestions);
                ps.setInt(4, score);
                ps.setDouble(5, percentage);

                ps.executeUpdate();

                System.out.printf(
                    "Result saved successfully. Percentage: %.2f%%%n",
                    percentage
                );
            }

        } catch (NumberFormatException e) {

            System.out.println("Please enter valid numbers.");

        } catch (SQLException e) {

            System.out.println("Could not save result: " + e.getMessage());
            System.out.println("Oracle error code: " + e.getErrorCode());
        }
    }

    static void showHighestScore() {

        String sql = """
            SELECT STUDENT_ID, QUIZ_NAME, SCORE,
                   TOTAL_QUESTIONS, PERCENTAGE
            FROM QUIZ_RESULTS
            WHERE PERCENTAGE = (
                SELECT MAX(PERCENTAGE)
                FROM QUIZ_RESULTS
            )
            """;

        try (Connection con = connect();
             Statement stmt = con.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            boolean found = false;

            System.out.println("\n----- HIGHEST SCORE -----");

            while (rs.next()) {

                found = true;

                System.out.printf(
                    "Student ID: %s | Quiz: %s | Score: %d/%d | Percentage: %.2f%%%n",
                    rs.getString("STUDENT_ID"),
                    rs.getString("QUIZ_NAME"),
                    rs.getInt("SCORE"),
                    rs.getInt("TOTAL_QUESTIONS"),
                    rs.getDouble("PERCENTAGE")
                );
            }

            if (!found) {
                System.out.println("No quiz results found.");
            }

        } catch (SQLException e) {

            System.out.println(
                "Could not retrieve highest score: " + e.getMessage()
            );
            System.out.println("Oracle error code: " + e.getErrorCode());
        }
    }

    static void showAbove80() {

        String sql = """
            SELECT STUDENT_ID, QUIZ_NAME, SCORE,
                   TOTAL_QUESTIONS, PERCENTAGE
            FROM QUIZ_RESULTS
            WHERE PERCENTAGE > 80
            ORDER BY PERCENTAGE DESC
            """;

        try (Connection con = connect();
             Statement stmt = con.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            boolean found = false;

            System.out.println("\n----- STUDENTS SCORING ABOVE 80% -----");

            while (rs.next()) {

                found = true;

                System.out.printf(
                    "Student ID: %s | Quiz: %s | Score: %d/%d | Percentage: %.2f%%%n",
                    rs.getString("STUDENT_ID"),
                    rs.getString("QUIZ_NAME"),
                    rs.getInt("SCORE"),
                    rs.getInt("TOTAL_QUESTIONS"),
                    rs.getDouble("PERCENTAGE")
                );
            }

            if (!found) {
                System.out.println("No students scored above 80%.");
            }

        } catch (SQLException e) {

            System.out.println(
                "Could not retrieve results: " + e.getMessage()
            );
            System.out.println("Oracle error code: " + e.getErrorCode());
        }
    }

    static void showAllResults() {

        String sql = """
            SELECT ID, STUDENT_ID, QUIZ_NAME,
                   TOTAL_QUESTIONS, SCORE, PERCENTAGE
            FROM QUIZ_RESULTS
            ORDER BY ID
            """;

        try (Connection con = connect();
             Statement stmt = con.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            boolean found = false;

            System.out.println("\n----- ALL QUIZ RESULTS -----");

            while (rs.next()) {

                found = true;

                System.out.printf(
                    "ID: %d | Student ID: %s | Quiz: %s | Score: %d/%d | Percentage: %.2f%%%n",
                    rs.getInt("ID"),
                    rs.getString("STUDENT_ID"),
                    rs.getString("QUIZ_NAME"),
                    rs.getInt("SCORE"),
                    rs.getInt("TOTAL_QUESTIONS"),
                    rs.getDouble("PERCENTAGE")
                );
            }

            if (!found) {
                System.out.println("No quiz results found.");
            }

        } catch (SQLException e) {

            System.out.println(
                "Could not retrieve results: " + e.getMessage()
            );
            System.out.println("Oracle error code: " + e.getErrorCode());
        }
    }

    public static void main(String[] args) {

        createTable();

        while (true) {

            System.out.println("\n===== QUIZ APPLICATION =====");
            System.out.println("1. Add Quiz Result");
            System.out.println("2. Display Highest Score");
            System.out.println("3. Display Results Above 80%");
            System.out.println("4. Display All Results");
            System.out.println("5. Exit");

            System.out.print("Enter your choice: ");

            String choice = sc.nextLine().trim();

            switch (choice) {

                case "1":
                    addResult();
                    break;

                case "2":
                    showHighestScore();
                    break;

                case "3":
                    showAbove80();
                    break;

                case "4":
                    showAllResults();
                    break;

                case "5":
                    System.out.println("Exiting Quiz Application.");
                    sc.close();
                    return;

                default:
                    System.out.println(
                        "Invalid choice. Enter a number from 1 to 5."
                    );
            }
        }
    }
}